def cut(s, start_marker, end_marker):
    i = s.find(start_marker); j = s.find(end_marker, i)
    assert i >= 0 and j > i, (start_marker[:40], end_marker[:40])
    return s[:i] + s[j:]

def rep(s, a, b, count=1):
    assert s.count(a) >= 1, a[:80]
    return s.replace(a, b) if count == 0 else s.replace(a, b, count)

